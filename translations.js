function setLanguage(lang) {
  if (!translations[lang]) return;

  document.documentElement.lang = lang;

  document.querySelectorAll("[data-i18n]").forEach(element => {
    const key = element.getAttribute("data-i18n");
    if (Object.prototype.hasOwnProperty.call(translations[lang], key)) {
      element.textContent = translations[lang][key];
    }
  });

  document.querySelectorAll("[data-i18n-attr]").forEach(element => {
    const mapping = element.getAttribute("data-i18n-attr");
    mapping.split(",").forEach(pair => {
      const [attribute, key] = pair.trim().split(":");
      if (attribute && key && translations[lang][key]) {
        element.setAttribute(attribute, translations[lang][key]);
      }
    });
  });

  document.querySelectorAll(".language-switcher button").forEach(button => {
    button.classList.toggle("active", button.dataset.lang === lang);
  });

  try {
    localStorage.setItem("dachadesign-language", lang);
  } catch (error) {
    // Language switching still works if storage is unavailable.
  }
}

document.addEventListener("DOMContentLoaded", () => {
  document.querySelectorAll(".language-switcher button").forEach(button => {
    button.addEventListener("click", () => {
      setLanguage(button.dataset.lang);
    });
  });

  let savedLanguage = "uk";
  try {
    savedLanguage = localStorage.getItem("dachadesign-language") || "uk";
  } catch (error) {
    // Use Ukrainian by default.
  }

  setLanguage(savedLanguage);
});
